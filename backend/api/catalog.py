def providers_for(country_code: str) -> list[dict]:
    """Fournisseurs internationaux + ceux du pays demandé."""
    code = (country_code or "").upper()
    return [
        {
            "name": p["name"],
            "category": p["category"],
            "plans": p.get("plans") or [],
        }
        for p in CATALOG
        if "*" in p["countries"] or code in p["countries"]
    ]
